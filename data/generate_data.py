FIELDNAMES = [
    "property_id",
    "title",
    "location",
    "property_type",
    "bedrooms",
    "bathrooms",
    "price",
    "possession_date",
    "status",
    "amenities",
    "investment_score",
    "family_score",
]

def generate_properties_dataset(filepath: str = None) -> List[Dict[str, Any]]:
    """
    Generates properties data and saves to a CSV file.
    If filepath is None, saves to data/properties.csv relative to project root.
    Returns the list of property dictionaries.
    """
    if filepath is None:
        base_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
        filepath = os.path.join(base_dir, "data", "properties.csv")

    os.makedirs(os.path.dirname(filepath), exist_ok=True)

    with open(filepath, mode="w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=FIELDNAMES)
        writer.writeheader()
        for prop in PROPERTIES_DATA:
            writer.writerow(prop)

    return PROPERTIES_DATA

if __name__ == "__main__":
    generated = generate_properties_dataset()
    print(f"Successfully generated {len(generated)} properties to data/properties.csv")
